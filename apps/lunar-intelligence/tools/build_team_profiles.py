"""
Extract real LOLA Site20 (5 m/px) E-W elevation profiles for team-analysis zones
(dist/arayuz_sonuc.json) that fall inside the Site20 tile. Zones outside the tile get none.

Usage: python tools/build_team_profiles.py <dir-with-site20-tifs>
Writes dist/team_profiles.js. Requires numpy, tifffile.
"""
import json, math, sys
from pathlib import Path
import numpy as np
import tifffile

R, PX, X0, Y0 = 1737400.0, 5.0, 65000.0, 126000.0
dist = Path(__file__).resolve().parent.parent / "dist"
elev = tifffile.imread(sorted(Path(sys.argv[1] if len(sys.argv) > 1 else ".").glob("*surf*.tif"))[0]).astype("float64")
data = json.loads((dist / "arayuz_sonuc.json").read_text(encoding="utf-8", errors="replace"))
out = {}
for z in data["en_verimli"] + data["en_riskli"]:
    r = 2 * R * math.tan(math.radians(90 + z["lat"]) / 2)
    x, y = r * math.sin(math.radians(z["lon"])), r * math.cos(math.radians(z["lon"]))
    row, col = int((Y0 - y) / PX), int((x - X0) / PX)
    if not (0 <= row < elev.shape[0] and 20 <= col < elev.shape[1] - 21):
        print(z["id"], "outside Site20 tile"); continue
    cols = col - 20 + np.arange(81) * 0.5
    lo = np.floor(cols).astype(int); t = cols - lo
    prof = elev[row, lo] * (1 - t) + elev[row, lo + 1] * t
    out[z["id"]] = [round(float(v), 2) for v in prof - prof[0]]
    print(z["id"], "profile range", round(float(np.ptp(prof)), 2), "m")
(dist / "team_profiles.js").write_text("// GENERATED by tools/build_team_profiles.py from NASA LOLA Site20 — do not edit.\n"
                                       "export const teamProfiles=" + json.dumps(out) + ";\n", encoding="utf-8")
